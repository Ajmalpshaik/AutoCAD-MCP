"""One call for the shapes a draftsman asks for by name.

"A 200 flange, 8 holes on a 160 PCD." "A slot 120 long, 40 wide." "The flat
pattern for that 200 to 100 reducer." "A 1200 wide stair, 14 risers at 175."
Each is a page of construction geometry, and each is one call here.

The geometry is generated by the pure functions in ``acad/shapes.py`` and drawn
down the same engine ``autocad_batch_draw`` uses, so it is fast, it lands as one
undo step, and ``coords='ucs'`` works on all of it.
"""

from __future__ import annotations

from typing import Annotated, Any

from pydantic import Field, StrictInt

from ..acad import shapes as shape_library
from ..core.errors import AutocadError
from ..core.registry import dumps, mcp, tool_errors, tool_meta
from ._shared import COORDS_OPT
from .batch import draw_operations

# The catalogue, short enough to sit in the tool's own description so an agent
# never has to guess a name or a setting. Kept beside the registry it describes.
CATALOGUE = (
    "polygon (sides, radius) - regular polygon; inscribed=false measures to a flat\n"
    "hexagon (across_flats or across_corners) - a nut or bolt head, sized as a spanner reads it\n"
    "star (points, outer_radius) - inner_radius optional\n"
    "slot (length, width) - an obround slot, round both ends, one object\n"
    "rounded_rectangle (width, height, radius) - filleted corners, one object\n"
    "spiral (turns, start_radius, end_radius)\n"
    "bolt_circle (count, pitch_diameter, hole_diameter) - just the holes\n"
    "flange (outer_diameter, bolt_count, pitch_diameter, hole_diameter) - bore optional\n"
    "elbow (centreline_radius, angle, width) - pipe or duct bend in plan, with centreline\n"
    "duct_transition (width_in, width_out, length) - offset optional\n"
    "stair (risers, rise, going, width) - view='section' (default) or 'plan'\n"
    "ladder (height, width) - rungs or spacing\n"
    "grating (width, height, spacing) - direction='x' or 'y'\n"
    "truss (span, depth, panels) - parallel chord, Warren bracing\n"
    "zigzag (length, amplitude, cycles) - break line, insulation, spring\n"
    "steel_section (profile, depth, width) - profile i/h/c/l/t/shs/rhs/chs, plus web "
    "and flange_thickness\n"
    "cone_development (bottom_diameter, top_diameter, height) - the flat pattern for a "
    "reducer; top_diameter 0 for a full cone\n"
    "gear (teeth, pitch_diameter) - drawing-office convention; show_teeth=true adds an "
    "approximate tooth outline, not a true involute\n"
    "\nDrafting furniture (your office block is better when you have one — "
    "autocad_insert_block):\n"
    "detail_bubble (number, radius) - sheet= splits it, number over sheet\n"
    "section_mark (length) - cut line, arrows and a bubble each end; label=, flip=\n"
    "north_arrow (size) - points up before rotation\n"
    "scale_bar (scale, length) - length is on the PAPER, labels are the real distances\n"
    "level_mark (level) - spot level triangle; below=true for a soffit or invert\n"
    "revision_tag (number) - the numbered triangle"
)


@mcp.tool(name="autocad_make_shape", **tool_meta("Draw A Named Shape"))
@tool_errors
async def autocad_make_shape(
    shape: Annotated[
        str,
        Field(
            min_length=1,
            description=(
                "Which shape to draw. Each line below is the name and the settings it "
                "must be given; the rest are optional and listed in the error if you "
                "get one wrong.\n\n" + CATALOGUE
            ),
        ),
    ],
    settings: Annotated[
        dict[str, Any],
        Field(
            description=(
                'The shape\'s settings, e.g. {"outer_diameter": 200, "bolt_count": 8, '
                '"pitch_diameter": 160, "hole_diameter": 18, "bore": 100}. '
                "Every shape also takes 'origin' ([x, y], default [0, 0]) and most take "
                "'rotation' (degrees). Lengths are in the drawing's own units, so call "
                "autocad_status first."
            ),
        ),
    ],
    layer: Annotated[
        str | None,
        Field(
            default=None,
            description="Layer for the shape, created if missing. Passed to every part of it.",
        ),
    ] = None,
    color: Annotated[
        str | StrictInt | None,
        Field(default=None, description="Colour for the shape; omit to inherit from the layer."),
    ] = None,
    centreline_layer: Annotated[
        str | None,
        Field(
            default=None,
            description=(
                "Layer for the centre lines a shape produces - a flange's pitch circle, "
                "an elbow's centreline, a gear's pitch circle. Give it and they go on "
                "their own layer, as a drafter would have them."
            ),
        ),
    ] = None,
    dry_run: Annotated[
        bool,
        Field(
            default=False,
            description=(
                "Return the geometry it would draw, as autocad_batch_draw operations, "
                "and draw nothing. Use it to look first, or to take the operations, "
                "change something, and send them yourself."
            ),
        ),
    ] = False,
    coords: Annotated[str, COORDS_OPT] = "world",
) -> str:
    """Draw a shape from its name and its dimensions: flange, slot, stair, elbow, flat pattern.

    This is the "simple words to complex geometry" path. Give the shape's name
    and the few numbers that define it, and the whole thing is generated and
    drawn as one undo step — arcs stay arcs, a slot stays one object, a flat
    pattern comes out at the right girth.

    Lengths are in the drawing's own units. ``coords='ucs'`` draws the shape
    square to the modeller's own grid.

    Args:
        shape (str): the shape's name; the field description lists them all.
        settings (dict): that shape's dimensions, plus 'origin' and 'rotation'.
        layer (Optional[str]): target layer, created if missing.
        color (Optional[str | int]): colour, or omit for ByLayer.
        centreline_layer (Optional[str]): layer for the shape's centre lines.
        dry_run (bool): return the geometry, draw nothing.
        coords (str): 'world' or 'ucs'.

    Returns:
        str: JSON. Drawing: {"shape", "created", "failed", "handles",
             "layers_created", "elapsed_seconds", ...} as autocad_batch_draw
             reports. With dry_run: {"shape", "operations": [...],
             "entity_count"}.

    Examples:
        - Use when: "draw a 200 flange with 8 x M16 holes on a 160 PCD" —
          shape="flange".
        - Use when: "I need the flat pattern for a 200 to 100 reducer, 150 long"
          — shape="cone_development".
        - Use when: "a 1200 wide stair, 14 risers at 175, 280 going, in section".
        - Use when: "a 120 x 40 slot at 30 degrees" — one object, round ends.
        - Don't use when: the thing is a one-off outline you can give as points
          (autocad_batch_draw), or it is already a block in the drawing
          (autocad_insert_block).

    Error Handling:
        - An unknown shape name lists every shape there is.
        - A missing setting is named; so is a setting the shape does not take,
          with the full list of what it does take.
        - Dimensions that cannot make the shape are refused with the reason and
          the limit — a fillet bigger than half the side, a slot no longer than
          it is wide, a cone that opens past a full circle.
    """
    given = dict(settings or {})
    for key, value in (("layer", layer), ("color", color), ("centreline_layer", centreline_layer)):
        if value is not None and key not in given:
            given[key] = value
    # centreline_layer only means something to the shapes that draw centre lines.
    if "centreline_layer" in given:
        allowed = shape_library.SHAPES.get(str(shape).strip().lower().replace("-", "_"))
        if allowed is not None and "centreline_layer" not in allowed.__code__.co_varnames:
            given.pop("centreline_layer")

    try:
        operations = shape_library.build(shape, given)
    except ValueError as exc:
        raise AutocadError(str(exc)) from exc
    if not operations:  # pragma: no cover - every generator returns at least one
        raise AutocadError(f"'{shape}' produced no geometry from those settings.")

    name = str(shape).strip().lower().replace("-", "_")
    if dry_run:
        return dumps(
            {
                "shape": name,
                "dry_run": True,
                "entity_count": len(operations),
                "operations": operations,
                "hint": (
                    "Nothing was drawn. Call again with dry_run=false, or pass these "
                    "operations to autocad_batch_draw after changing them."
                ),
            }
        )

    result = await draw_operations(operations, return_handles=True, coords=coords)
    result["shape"] = name
    return dumps(result)
